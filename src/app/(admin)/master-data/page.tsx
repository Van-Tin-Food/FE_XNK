function emptyForm(config: EntityConfig): Record<string, string> {
  return Object.fromEntries(config.fields.filter((field) => !field.listOnly).map((field) => [field.key, field.defaultValue ?? ""]));
}

export default function MasterDataPage() {
  const { user, can } = useAuth();
  const { notify } = useSystemNotification();
  const { confirm } = useSystemConfirm();
  const { t } = useLanguage();
  const searchParams = useSearchParams();
  const [active, setActive] = useState<EntityKey>(() => {
    const requested = searchParams.get("catalog") as EntityKey | null;
    return requested && requested in ENTITY_CONFIG ? requested : "suppliers";
  });
  const [rows, setRows] = useState<DataRow[]>([]);
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [query, setQuery] = useState("");
  const [page, setPage] = useState(1);
  const [pageSize, setPageSize] = useState(DEFAULT_PAGE_SIZE);
  const [form, setForm] = useState<Record<string, string>>(() => emptyForm(ENTITY_CONFIG.suppliers));
  const [originalForm, setOriginalForm] = useState<Record<string, string>>({});
  const [editingId, setEditingId] = useState<string | null>(null);
  const config = ENTITY_CONFIG[active];
  const canView = (config.viewPermissions || []).some((fn) => can(fn));
  const canManage = (config.editPermissions || []).some((fn) => can(fn, "edit"));
  /** Giá trị hiện ở bảng: ô chọn hiện nhãn đã dịch. */
  const displayValue = (field: FieldConfig, row: DataRow) => {
    const raw = row[field.key];
    const value = raw === null || raw === undefined ? "" : String(raw);
    const option = field.options?.find((item) => item.value === value);
    return option ? t(option.labelKey) : value;
  };
  // Trường user được xem (bảng, tìm kiếm, form sửa). Form tạo mới vẫn hiện đủ để điền thông tin.
  const listFields = useMemo(
    () => config.fields.filter((field) => !field.sensitive || can(field.sensitive)),
    [config.fields, can],
  );
  const formFields = (editingId ? listFields : config.fields).filter((field) => !field.listOnly);
  const hasDedicatedCatalogRoute = (Object.keys(ENTITY_CONFIG) as string[]).includes(searchParams.get("catalog") || "");

  useEffect(() => {
    const requested = searchParams.get("catalog") as EntityKey | null;
    if (requested && requested in ENTITY_CONFIG && requested !== active) setActive(requested);
  }, [active, searchParams]);

  const loadRows = async () => {
    setLoading(true);
    try {
      setRows(await listDatabaseRows<DataRow>(config.endpoint));
    } catch (error) {
      notify(error instanceof Error ? error.message : t("catalogListLoadError", { catalog: t(config.titleKey) }), "error");
      setRows([]);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (!canView) return;
    setForm(emptyForm(config));
    setOriginalForm({});
    setEditingId(null);
    setQuery("");
    setPage(1);
    void loadRows();
    // Chỉ tải lại khi đổi loại danh mục hoặc quyền hiện tại.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [active, canView]);

  const filteredRows = useMemo(() => {
    const keyword = query.trim().toLocaleLowerCase("vi");
    if (!keyword) return rows;
    return rows.filter((row) => listFields.some((field) => displayValue(field, row).toLocaleLowerCase("vi").includes(keyword)));
    // displayValue chỉ phụ thuộc listFields + ngôn ngữ (t).
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [listFields, query, rows, t]);
  const { totalPages, safePage, items: displayedRows, from, to } = paginateItems(filteredRows, page, pageSize);

  const beginCreate = () => {
    setEditingId(null);
    setForm(emptyForm(config));
    setOriginalForm({});
  };

  // Màn nhỏ: form nằm dưới danh sách, bấm Sửa thì cuộn tới form để không phải tự tìm.
  const formRef = useRef<HTMLFormElement>(null);
  const beginEdit = async (row: DataRow) => {
    if (!canManage) return;
    const id = String(row[config.idField] ?? "");
    if (!id) return;
    try {
      const latest = await getDatabaseRow<DataRow>(config.endpoint, id);
      setEditingId(id);
      const nextForm = Object.fromEntries(config.fields.filter((field) => !field.listOnly).map((field) => [field.key, String(latest[field.key] ?? row[field.key] ?? "")])) as Record<string, string>;
      setForm(nextForm);
      setOriginalForm(nextForm);
      if (window.matchMedia("(max-width: 1535px)").matches) {
        window.requestAnimationFrame(() => formRef.current?.scrollIntoView({ behavior: "smooth", block: "start" }));
      }
    } catch (error) {
      notify(error instanceof Error ? error.message : t("catalogItemLoadError", { catalog: t(config.singularKey) }), "error");
    }
  };

  const save = async (event: React.FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    const missing = config.fields.filter((field) => field.required && !field.autoGenerated && !field.listOnly && !form[field.key]?.trim());
    if (missing.length > 0) return notify(t("enterRequiredFields", { fields: missing.map((field) => t(field.labelKey)).join(", ") }), "warning");
    const approved = await confirm({
      title: editingId ? t("confirmCatalogEdit", { catalog: t(config.singularKey) }) : t("confirmCatalogAdd", { catalog: t(config.singularKey) }),
      message: editingId ? t("saveChangesFor", { id: editingId }) : t("addCatalogItem", { catalog: t(config.singularKey), id: "tự động" }),
      confirmText: editingId ? t("save") : t("addNew"),
    });
    if (!approved) return;
    setSaving(true);
    try {
      const fieldChanges = formFields
        .filter((field) => !field.autoGenerated && field.key !== config.idField)
        .flatMap((field) => {
          const before = String(originalForm[field.key] ?? "").trim();
          const after = String(form[field.key] ?? "").trim();
          if (!editingId || before === after) return [];
          // Nhật ký xem được bởi role khác (IT), nên không ghi giá trị trường nhạy cảm.
          if (field.sensitive) return [`${t(field.labelKey)}: (đã thay đổi)`];
          return [`${t(field.labelKey)}: ${before || "(trống)"} → ${after || "(trống)"}`];
        });
      const sensitiveKeys = new Set(config.fields.filter((field) => field.sensitive).map((field) => field.key));
      if (editingId) {
        // Chỉ gửi trường đang hiện trên form sửa để không ghi đè dữ liệu nhạy cảm user không xem được.
        const editableKeys = new Set(formFields.map((field) => field.key));
        const changes = Object.fromEntries(Object.entries(form).filter(([key]) => key !== config.idField && editableKeys.has(key)));
        await updateDatabaseRow(config.endpoint, editingId, changes);
      } else {
        const createPayload = Object.fromEntries(Object.entries(form).filter(([key]) => key !== config.idField));
        await createDatabaseRow(config.endpoint, createPayload);
      }
      recordActivity(user, {
        action: editingId ? "UPDATE_MASTER_DATA" : "CREATE_MASTER_DATA",
        location: `/master-data/${config.endpoint}`,
        detail: editingId
          ? `Cập nhật ${t(config.singularKey)} ${editingId}; thay đổi: ${fieldChanges.join(" | ") || "Không thay đổi"}`
          : `Tạo ${t(config.singularKey)} (ID tự động); dữ liệu: ${Object.entries(form).filter(([key, value]) => key !== config.idField && String(value).trim()).map(([key, value]) => `${key}=${sensitiveKeys.has(key) ? "(đã nhập)" : String(value).trim()}`).join(" | ") || "Không có dữ liệu bổ sung"}`,
      });
      notify(editingId ? t("catalogUpdated", { catalog: t(config.singularKey) }) : t("catalogAdded", { catalog: t(config.singularKey) }), "success");
      beginCreate();
      await loadRows();
    } catch (error) {
      notify(error instanceof Error ? error.message : t("catalogSaveError", { catalog: t(config.singularKey) }), "error");
    } finally {
      setSaving(false);
    }
  };

  if (!canView) {
    return <div className="flex min-h-[55vh] items-center justify-center text-sm font-medium text-error-600">{t("adminAllOnly")}</div>;
  }

  return (
    <section className="space-y-5">
      <div>
        <h1 className="text-2xl font-semibold text-gray-800 dark:text-white/90">{hasDedicatedCatalogRoute ? t(config.titleKey) : t("masterDataManagement")}</h1>
        <p className="mt-1 text-sm text-gray-500 dark:text-gray-400">{t("masterDataDescription")}</p>
      </div>
      {!hasDedicatedCatalogRoute && (
        <div className="flex flex-wrap gap-1 rounded-xl border border-gray-200 bg-white p-1.5 dark:border-gray-800 dark:bg-gray-900">
          {(Object.keys(ENTITY_CONFIG) as EntityKey[]).map((key) => (
            <button key={key} type="button" onClick={() => setActive(key)} className={`flex-1 rounded-lg px-3 py-2.5 text-sm font-semibold sm:flex-none sm:px-4 ${active === key ? "bg-brand-500 text-white" : "text-gray-600 hover:bg-gray-100 dark:text-gray-300 dark:hover:bg-gray-800"}`}>{t(ENTITY_CONFIG[key].titleKey)}</button>
          ))}
        </div>
      )}
      <div className="grid gap-5 2xl:grid-cols-[minmax(0,1.6fr)_minmax(320px,0.8fr)]">
        <div className="min-w-0 overflow-hidden rounded-2xl border border-gray-200 bg-white dark:border-gray-800 dark:bg-gray-900">
          <div className="flex flex-col gap-3 border-b border-gray-100 p-4 dark:border-gray-800 sm:flex-row sm:items-center sm:justify-between">
            <div><h2 className="font-semibold text-gray-800 dark:text-white">{t("catalogList", { catalog: t(config.titleKey) })}</h2><p className="text-xs text-gray-400">{t("dataCount", { count: filteredRows.length })}</p></div>
            <div className="flex w-full min-w-0 gap-2 sm:w-auto"><SearchSuggestions value={query} onChange={(value) => { setQuery(value); setPage(1); }} suggestions={rows.flatMap((row) => listFields.map((field) => displayValue(field, row)))} placeholder={t("searchPlaceholderShort")} ariaLabel={t("searchPlaceholderShort")} className="h-10 min-w-0 w-full rounded-xl border border-gray-200 bg-gray-50 px-3 text-sm outline-none focus:border-brand-400 dark:border-gray-700 dark:bg-gray-900 dark:text-white" /><button type="button" onClick={() => void loadRows()} className="shrink-0 whitespace-nowrap rounded-xl border border-gray-200 px-3 text-sm font-semibold text-gray-600 dark:border-gray-700 dark:text-gray-300">{t("refreshData")}</button></div>
          </div>
          {loading ? <div className="flex min-h-60 items-center justify-center"><span className="h-9 w-9 animate-spin rounded-full border-2 border-brand-500 border-t-transparent" /></div> : (
            <>
            <div className="divide-y divide-gray-100 md:hidden dark:divide-gray-800">
              {displayedRows.map((row, rowIndex) => (
                <div key={`${active}-card-${String(row[config.idField] ?? "row")}-${rowIndex}`} className="space-y-2 p-4">
                  <dl className="grid grid-cols-[minmax(0,7rem)_minmax(0,1fr)] gap-x-3 gap-y-1.5 text-sm">
                    {listFields.map((field) => (
                      <React.Fragment key={field.key}>
                        <dt className="text-xs text-gray-400">{t(field.labelKey)}</dt>
                        <dd className="min-w-0 break-words text-gray-700 dark:text-gray-300">{displayValue(field, row) || "—"}</dd>
                      </React.Fragment>
                    ))}
                  </dl>
                  {canManage && <button type="button" onClick={() => void beginEdit(row)} className="w-full rounded-lg border border-brand-200 px-3 py-2 text-xs font-semibold text-brand-600 hover:bg-brand-50">{t("edit")}</button>}
                </div>
              ))}
            </div>
            <div className="hidden overflow-x-auto md:block"><table className="w-full min-w-[640px] table-fixed"><thead className="bg-gray-50 text-left text-xs uppercase text-gray-500 dark:bg-gray-900/50"><tr>{listFields.map((field) => <th key={field.key} className="px-4 py-3">{t(field.labelKey)}</th>)}{canManage && <th className="w-28 px-4 py-3 text-right">{t("actions")}</th>}</tr></thead><tbody className="divide-y divide-gray-100 dark:divide-gray-800">{displayedRows.map((row, rowIndex) => <tr key={`${active}-${String(row[config.idField] ?? "row")}-${rowIndex}`} className="hover:bg-gray-50/60 dark:hover:bg-white/[0.02]">{listFields.map((field) => <td key={field.key} className="max-w-56 truncate px-4 py-3 text-sm text-gray-700 dark:text-gray-300" title={displayValue(field, row)}>{displayValue(field, row) || "—"}</td>)}{canManage && <td className="px-4 py-3 text-right"><button type="button" onClick={() => void beginEdit(row)} className="rounded-lg border border-brand-200 px-3 py-1.5 text-xs font-semibold text-brand-600 hover:bg-brand-50">{t("edit")}</button></td>}</tr>)}</tbody></table></div>
            {displayedRows.length === 0 && <p className="py-10 text-center text-sm text-gray-400">{t("noData")}</p>}
            </>
          )}
          {displayedRows.length > 0 && <PaginationControls page={safePage} totalPages={totalPages} pageSize={pageSize} totalItems={filteredRows.length} from={from} to={to} onPageChange={setPage} onPageSizeChange={(value) => { setPageSize(value); setPage(1); }} />}
        </div>
        <form ref={formRef} onSubmit={save} className={`h-fit scroll-mt-20 rounded-2xl 2xl:sticky 2xl:top-20 2xl:z-20 border border-gray-200 bg-white p-5 shadow-theme-xs dark:border-gray-800 dark:bg-gray-900 ${!canManage ? "pointer-events-none opacity-60" : ""}`}>
          <div className="mb-5 flex items-start justify-between gap-3"><div><h2 className="font-semibold text-gray-800 dark:text-white">{editingId ? t("editCatalog", { catalog: t(config.singularKey) }) : t("addCatalog", { catalog: t(config.singularKey) })}</h2><p className="mt-1 text-xs text-gray-400">{editingId ? editingId : t("enterInformationBelow")}</p></div>{editingId && <button type="button" onClick={beginCreate} className="text-xs font-semibold text-gray-500">{t("cancelEdit")}</button>}</div>
          <div className="space-y-4">{formFields.filter((field) => !field.autoGenerated || Boolean(editingId)).map((field) => <label key={field.key} className="block text-sm font-medium text-gray-700 dark:text-gray-300">{t(field.labelKey)}{field.required && <span className="text-error-500"> *</span>}{field.autoGenerated && !editingId && <span className="ml-1 text-xs font-normal text-gray-400">(tự động)</span>}{field.options ? <select value={form[field.key] || ""} onChange={(event) => setForm((current) => ({ ...current, [field.key]: event.target.value }))} className="mt-1.5 h-10 w-full rounded-xl border border-gray-200 bg-gray-50 px-3 text-sm outline-none focus:border-brand-400 dark:border-gray-700 dark:bg-gray-900 dark:text-white">{field.options.map((option) => <option key={option.value} value={option.value}>{t(option.labelKey)}</option>)}</select> : field.multiline ? <textarea value={form[field.key] || ""} disabled={Boolean(editingId && field.key === config.idField)} onChange={(event) => setForm((current) => ({ ...current, [field.key]: event.target.value }))} rows={3} className="mt-1.5 w-full rounded-xl border border-gray-200 bg-gray-50 px-3 py-2 text-sm outline-none focus:border-brand-400 disabled:opacity-60 dark:border-gray-700 dark:bg-gray-900 dark:text-white" /> : <input type={field.key === "email" ? "email" : "text"} value={form[field.key] || ""} disabled={Boolean(editingId && field.key === config.idField)} onChange={(event) => setForm((current) => ({ ...current, [field.key]: field.uppercase ? event.target.value.toUpperCase() : event.target.value }))} className="mt-1.5 h-10 w-full rounded-xl border border-gray-200 bg-gray-50 px-3 text-sm outline-none focus:border-brand-400 disabled:opacity-60 dark:border-gray-700 dark:bg-gray-900 dark:text-white" />}{field.hintKey && <span className="mt-1 block text-xs font-normal text-gray-400">{t(field.hintKey)}</span>}</label>)}</div>
          <button type="submit" disabled={saving} className="mt-5 w-full rounded-xl bg-brand-500 px-4 py-2.5 text-sm font-semibold text-white hover:bg-brand-600 disabled:opacity-60">{saving ? t("saving") : editingId ? t("save") : t("addNew")}</button>
        </form>
      </div>
    </section>
  );
}
