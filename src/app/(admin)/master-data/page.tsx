type EntityKey = "suppliers" | "carriers" | "warehouses" | "paymentCategories";
type DataRow = Record<string, unknown>;

interface FieldConfig {
  key: string;
  labelKey: string;
  required?: boolean;
  multiline?: boolean;
  autoGenerated?: boolean;
  /** Trường nhạy cảm: chỉ hiện khi xem/sửa nếu user có quyền xem chức năng này; form tạo mới vẫn hiện. */
  sensitive?: PermissionFunction;
  /** Ô chọn: giá trị lưu + khoá bản dịch nhãn (bảng hiện nhãn đã dịch). */
  options?: Array<{ value: string; labelKey: string }>;
  /** Giá trị mặc định khi thêm mới. */
  defaultValue?: string;
  /** Tự đổi chữ in hoa khi gõ (mã). */
  uppercase?: boolean;
  /** Chỉ hiện ở bảng (BE tính), không có trên form. */
  listOnly?: boolean;
  /** Gợi ý dưới ô nhập. */
  hintKey?: string;
}

interface EntityConfig {
  titleKey: string;
  singularKey: string;
  endpoint: string;
  idField: string;
  fields: FieldConfig[];
  /** Quyền xem (đạt một là đủ, mức view). */
  viewPermissions?: PermissionFunction[];
  /** Quyền thêm / sửa (đạt một là đủ, mức edit). */
  editPermissions?: PermissionFunction[];
}

